def atlas(geo, original, c, accent, glow_original=None, emit_inlays=False):
    """Repaint cube face nets at exact authored UVs; preserve open alpha masks."""
    im=blank(original.size);glow=blank(original.size);d=ImageDraw.Draw(im)
    bounds=[]
    for bone in geo['minecraft:geometry'][0]['bones']:
        for cube in bone.get('cubes',[]):
            uv=cube.get('uv');size=cube['size'];w,h,z=[max(1,math.ceil(v)) for v in size]
            if not isinstance(uv,list):continue # explicit face atlases are reviewed separately
            u,v=uv
            for face,(x,y,fw,fh) in enumerate([(u+z,v,w,z),(u+z+w,v,w,z),(u,v+z,z,h),(u+z,v+z,w,h),(u+z+w,v+z,z,h),(u+2*z+w,v+z,w,h)]):
                x,y=int(x),int(y); bounds.append([x,y,x+fw,y+fh])
                assert x>=0 and y>=0 and x+fw<=im.width and y+fh<=im.height,(bone['name'],uv,size,im.size)
                for yy in range(fh):
                    for xx in range(fw):
                        a=original.getpixel((x+xx,y+yy))[3]
                        if not a:continue
                        k=1.38 if yy==0 else .49 if yy==fh-1 else 1.09 if xx==0 else .64 if xx==fw-1 else [.82,1.04,1.18][min(2,xx*3//fw)]
                        col=shade(c,k)
                        # Layer seams and plate bevels, no per-pixel white noise.
                        if fh>=6 and yy in [fh//2,fh//2+1]:col=shade(c,.59 if yy==fh//2 else 1.16)
                        if fw>=5 and face==3 and 'Head' not in bone['name'] and xx==fw//2 and 2<=yy<fh-2:
                            col=shade(accent,1.12 if yy%4 else 1.5)
                            if emit_inlays:glow.putpixel((x+xx,y+yy),col[:3]+(a,))
                        im.putpixel((x+xx,y+yy),col[:3]+(a,))
                        if glow_original and glow_original.getpixel((x+xx,y+yy))[3]:
                            col=shade(accent,1.14 if xx%3 else 1.5);im.putpixel((x+xx,y+yy),col[:3]+(a,));glow.putpixel((x+xx,y+yy),col)
    return im,glow,bounds

