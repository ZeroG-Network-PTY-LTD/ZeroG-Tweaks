def animate(key, frame, category):
    dst=TEXTURES/(key+'.png');meta=dst.with_suffix('.png.mcmeta')
    if not meta.exists():return save(key,frame,category)
    info=json.loads(meta.read_text()).get('animation',{});old=Image.open(dst)
    fw=info.get('width',old.width);fh=info.get('height',fw)
    count=old.height//fh
    sheet=blank((32,32*count))
    # Keep animation indexes/timing. Animate only small selected bright accents,
    # never jitter the plant silhouette or resample the old frame.
    for n in range(count):
        current=frame.copy()
        for y in range(32):
            for x in range(32):
                pix=current.getpixel((x,y))
                if pix[3] and min(pix[:3])>140 and max(pix[:3])>220:
                    current.putpixel((x,y),shade(pix[:3],[.87,1,1.09,1][n%4])[:3]+(pix[3],))
        sheet.paste(current,(0,n*32))
    # All existing implicit square animations continue to be 32px square.
    if 'width' in info or 'height' in info:
        info['width']=32;info['height']=32;obj=json.loads(meta.read_text());obj['animation']=info
        meta.write_text(json.dumps(obj,indent=2)+'\n')
    return save(key,sheet,category,{'frame_count':count,'frame_size':32,'timing_preserved':True})

