def native_crop(theme,id,age):
    """Seven anatomical crop silhouettes, not one recoloured fern template.

    Native 32px grid. Stage 0/1 establish leaves, stage 2 buds/young fruit,
    stage 3 the harvest anatomy. Fruit colours match the approved food sprites.
    The stakes below are pictured plant stems, not an added gameplay requirement.
    """
    greens=[(99,166,155),(76,156,120),(65,161,150),(103,146,118),(100,164,184),(153,167,90)]
    fruits=[(172,128,235),(240,141,81),(239,129,174),(245,147,68),(245,180,102),(213,128,211)]
