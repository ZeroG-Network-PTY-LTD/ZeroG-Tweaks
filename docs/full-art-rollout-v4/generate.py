def baseline():
    path=BASE/'baseline-head-textures.json'
    if path.exists():return json.loads(path.read_text())
    git=git_command(args.code);commit=subprocess.check_output(git+['rev-parse','HEAD']).decode().strip()
    archive=subprocess.check_output(git+['archive',commit,'src/main/resources/assets/zerog_tweaks/textures'])
    hashes={}
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            if member.isfile() and member.name.endswith('.png'):
                hashes[member.name.removeprefix('src/main/resources/')]=hashlib.sha256(tar.extractfile(member).read()).hexdigest()
    result={'commit':commit,'meaning':'immutable pre-work code HEAD, not last generated bytes','textures':hashes}
    path.write_text(json.dumps(result,indent=2)+'\n');return result

def functions(path, names, constants=()):
    """Load audited drawing functions only: no top-level asset/data writes."""
    tree = ast.parse(path.read_text())
    selected = [node for node in tree.body if isinstance(node, ast.FunctionDef)
                and node.name in names or isinstance(node, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id in constants for t in node.targets)]
    ns = dict(Image=Image, ImageDraw=ImageDraw, colorsys=colorsys, math=math,
              random=random, hashlib=hashlib, themes=['moon','mars','cerulon','skarn','eidolon','solvane'])
    exec(compile(ast.Module(body=selected, type_ignores=[]), str(path), 'exec'), ns)
    REUSED.append({'generator':path.relative_to(DOCS.parent).as_posix(), 'sha256':digest(path), 'functions':names})
    return ns

def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def colour(value): return tuple(bytes.fromhex(value.lstrip('#')))
def shade(c, level=1):
    if tuple(c[:3]) in COLOR_RAMPS:
        ramp=RAMPS[COLOR_RAMPS[tuple(c[:3])]]
        index=0 if level<.43 else 1 if level<.7 else 2 if level<.91 else 3 if level<1.15 else 4 if level<1.4 else 5
        return tuple(bytes.fromhex(ramp[index]))+(255,)
    target = (44,33,81) if level < 1 else (255,241,211)
    mix = min(.27, abs(level-1)*.43)
    return tuple(round(min(255,max(0,v*level))*(1-mix)+t*mix) for v,t in zip(c,target))+(255,)
def blank(size=(32,32)): return Image.new('RGBA',size)
def crystal(d,x,y,c,scale=3):
    d.polygon([(x,y-scale),(x+scale,y),(x+1,y+scale),(x-scale,y+1)],fill=shade(c,.55))
    d.polygon([(x,y-scale+1),(x+scale-1,y),(x,y+1),(x-scale+1,y)],fill=shade(c,1.15))
    d.line((x,y-scale+1,x-1,y),fill=shade(c,1.65))
    d.point((x+1,y+1),fill=shade(c,.78))

def save(key, im, category, contract=None, allow_new=False):
    relative = 'assets/zerog_tweaks/textures/'+key+'.png'
    dst = RES / relative
    if not dst.exists() and not allow_new: return False
    before = digest(dst) if dst.exists() else None
    src = BASE/'source'/relative
    src.parent.mkdir(parents=True,exist_ok=True)
    im.save(src)
    payload = src.read_bytes()
    targets = [dst]
    # Enumerate every existing resource layer, rather than assuming one override.
    for pack in (RES/'resourcepacks').glob('*'):
        if (pack/relative).exists() or key.endswith('_glowmask') and (pack/relative.replace('_glowmask.png','.png')).exists(): targets.append(pack/relative)
    for target in targets: target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(payload)
    meta = dst.with_suffix('.png.mcmeta')
    if meta.exists():
        src.with_suffix('.png.mcmeta').write_bytes(meta.read_bytes())
        for target in targets[1:]: target.with_suffix('.png.mcmeta').write_bytes(meta.read_bytes())
    ROWS.append({'path':relative,'category':category,'sha256':digest(src), 'rerun_previous_sha256':before,
                 'size':list(im.size),'alpha_bounds':im.getbbox(),'contract':contract,
                 'layers':[t.relative_to(RES).as_posix() for t in targets]})
    TILES.append((key, im.crop((0,0,im.width,min(im.width,im.height)))))
    return True

